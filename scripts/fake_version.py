#!/usr/bin/env python3
"""
伪装内核版本串，使 /proc/version 与原厂完全一致

原理（v3 —— 只改 UTS_VERSION 的唯一源头）
=========================================

ACK 6.12 的版本串链路：

    scripts/mkcompile_h
        └─> include/generated/compile.h      #define UTS_VERSION "#1 SMP PREEMPT <日期>"
             │
             ├─> init/version-timestamp.c    linux_banner[] = "Linux version " UTS_RELEASE ... UTS_VERSION "\\n"
             └─> init/version.c              init_uts_ns.name.version = UTS_VERSION

两条 banner 都引用同一个 UTS_VERSION 宏。
只要 compile.h 里的宏值统一，编译后内核里就只有一份完整文本。

旧版（v1/v2）在"消费端"逐处替换，容易漏：
  - v1 只改了 version-timestamp.c，version.c 没改 -> 两条 banner 长短不一
  - v2 的正则 (?!\\s*") 跳过了 `UTS_VERSION "\\n"` 这种写法 -> 没替换到

v3 的做法：
  1) 若 include/generated/compile.h 已存在，直接重定义其中的 UTS_VERSION
  2) 同时写入 include/generated/utsrelease.h 的 UTS_RELEASE
  3) 再在 version-timestamp.c / version.c 里做兜底替换（严格模式）

  并且提供 verify 子命令：改完后自检源码里 UTS_VERSION 只被定义一次。

用法：
  python3 fake_version.py <内核源码根> [版本串|@文件]
  python3 fake_version.py verify <内核源码根>
"""
import sys
import os
import re

OFFICIAL_VER = '6.12.69-android16-6-g43b5ab7e247d-abogki561813157-4k'
OFFICIAL_COMPILER = (
    'Android (14043575, +pgo, +bolt, +lto, +mlgo, based on r536225) '
    'clang version 19.0.1 '
    '(https://android.googlesource.com/toolchain/llvm-project '
    'b3a530ec6537146650e42be89f1089e9a3588460), LLD 19.0.1'
)
OFFICIAL_UTS_VERSION = '#1 SMP PREEMPT Tue Sep  8 15:08:49 UTC 2026'


def read_proc_version(path):
    """从 uname.txt / /proc/version 提取 release 与 UTS_VERSION"""
    raw = open(path, 'rb').read()
    if raw[:2] == b'\x1f\x8b':
        import gzip
        raw = gzip.decompress(raw)
    text = raw.decode('utf-8', 'replace')

    rel = uts = ''
    for line in text.splitlines():
        if 'Linux version' not in line:
            continue
        m = re.search(r'Linux version (\S+)', line)
        if m:
            rel = m.group(1)
        m2 = re.search(r'\)\s*(#\S.*?)\s*$', line)
        if m2:
            uts = m2.group(1).strip()
        break
    return rel, uts


def write_if_changed(path, new, tag):
    old = open(path, encoding='utf-8', errors='replace').read()
    if old == new:
        print(f'  = {tag}: 无需修改')
        return False
    open(path, 'w', encoding='utf-8').write(new)
    print(f'  ✓ {tag}: 已修改')
    return True


def patch_generated(root, ver, uts_version):
    """核心：直接覆盖 include/generated/ 下的定义"""
    changed = 0
    gen = os.path.join(root, 'include', 'generated')

    # --- compile.h : UTS_VERSION 的唯一权威定义 ---
    ch = os.path.join(gen, 'compile.h')
    if os.path.exists(ch):
        src = open(ch, encoding='utf-8', errors='replace').read()
        pat = re.compile(r'^[ \t]*#[ \t]*define[ \t]+UTS_VERSION[ \t]+.*$',
                         re.MULTILINE)
        if pat.search(src):
            new = pat.sub(f'#define UTS_VERSION "{uts_version}"', src, count=1)
        else:
            # 没有就追加
            new = src.rstrip('\n') + f'\n#define UTS_VERSION "{uts_version}"\n'
        if write_if_changed(ch, new, 'include/generated/compile.h'):
            changed += 1
    else:
        # 文件不存在就创建（setlocalversion 之后会被覆盖，所以还要靠 verify 兜底）
        os.makedirs(gen, exist_ok=True)
        with open(ch, 'w', encoding='utf-8') as f:
            f.write('/* generated by fake_version.py */\n')
            f.write(f'#define UTS_VERSION "{uts_version}"\n')
        print(f'  ✓ include/generated/compile.h: 已创建')
        changed += 1

    # --- utsrelease.h : UTS_RELEASE ---
    ur = os.path.join(gen, 'utsrelease.h')
    if os.path.exists(ur):
        src = open(ur, encoding='utf-8', errors='replace').read()
        new = re.sub(r'^[ \t]*#[ \t]*define[ \t]+UTS_RELEASE[ \t]+.*$',
                     f'#define UTS_RELEASE "{ver}"', src, flags=re.MULTILINE)
        if write_if_changed(ur, new, 'include/generated/utsrelease.h'):
            changed += 1
    else:
        os.makedirs(gen, exist_ok=True)
        with open(ur, 'w', encoding='utf-8') as f:
            f.write(f'#define UTS_RELEASE "{ver}"\n')
        print(f'  ✓ include/generated/utsrelease.h: 已创建')
        changed += 1

    return changed


def patch_sources(root, ver, uts_version):
    """源码兜底：把 linux_banner / init_uts_ns 里的宏引用全部换成字面量"""
    changed = 0

    vf = os.path.join(root, 'init', 'version-timestamp.c')
    if os.path.exists(vf):
        src = open(vf, encoding='utf-8', errors='replace').read()
        orig = src
        # UTS_RELEASE 一律换字面量
        src = re.sub(r'"Linux version "\s*UTS_RELEASE',
                     f'"Linux version " "{ver}"', src)
        src = re.sub(r'(?<![\w"])UTS_RELEASE(?![\w"])', f'"{ver}"', src)
        # UTS_VERSION 一律换字面量（不加否定前瞻，务必替换干净）
        src = re.sub(r'(?<![\w"])UTS_VERSION(?![\w"])', f'"{uts_version}"', src)
        # LINUX_COMPILER 换字面量
        src = re.sub(r'(?<![\w"])LINUX_COMPILER(?![\w"])',
                     f'"{OFFICIAL_COMPILER}"', src)
        if write_if_changed(vf, src, 'init/version-timestamp.c'):
            changed += 1
        else:
            print('  ! version-timestamp.c 无变化')

    vc = os.path.join(root, 'init', 'version.c')
    if os.path.exists(vc):
        src = open(vc, encoding='utf-8', errors='replace').read()
        src = re.sub(r'(?<![\w"])UTS_RELEASE(?![\w"])', f'"{ver}"', src)
        src = re.sub(r'(?<![\w"])UTS_VERSION(?![\w"])', f'"{uts_version}"', src)
        src = re.sub(r'(?<![\w"])LINUX_COMPILER(?![\w"])',
                     f'"{OFFICIAL_COMPILER}"', src)
        if write_if_changed(vc, src, 'init/version.c'):
            changed += 1
        else:
            print('  ! version.c 无变化')

    return changed


def verify(root):
    """自检：确认源码里不再有 UTS_VERSION / UTS_RELEASE 的裸宏引用"""
    problems = []
    for rel in ('init/version-timestamp.c', 'init/version.c'):
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            continue
        for i, line in enumerate(open(p, encoding='utf-8', errors='replace'), 1):
            s = line.strip()
            if s.startswith(('#', '/*', '*', '//')):
                continue
            if re.search(r'(?<![\w"])UTS_VERSION(?![\w"])', line):
                problems.append(f'{rel}:{i} 仍有 UTS_VERSION 宏引用')
            if re.search(r'(?<![\w"])UTS_RELEASE(?![\w"])', line):
                problems.append(f'{rel}:{i} 仍有 UTS_RELEASE 宏引用')

    ch = os.path.join(root, 'include', 'generated', 'compile.h')
    if os.path.exists(ch):
        txt = open(ch, encoding='utf-8', errors='replace').read()
        n = len(re.findall(r'^[ \t]*#[ \t]*define[ \t]+UTS_VERSION', txt, re.MULTILINE))
        if n != 1:
            problems.append(f'include/generated/compile.h: UTS_VERSION 定义了 {n} 次')

    if problems:
        print('✗ 自检失败：')
        for p in problems:
            print('   ', p)
        return 1
    print('✓ 自检通过：源码里已无 UTS_VERSION / UTS_RELEASE 裸宏引用')
    return 0


def main():
    if len(sys.argv) >= 3 and sys.argv[1] == 'verify':
        return verify(sys.argv[2])

    root = sys.argv[1] if len(sys.argv) > 1 else '.'
    arg = sys.argv[2].strip() if len(sys.argv) > 2 else ''

    ver = arg
    uts_version = ''

    if arg.startswith('@'):
        path = arg[1:]
        try:
            ver, uts_version = read_proc_version(path)
            print(f'从 {path} 读取:')
            print(f'  release     = {ver}')
            print(f'  uts_version = {uts_version}')
        except Exception as e:
            print(f'⚠ 读取 {path} 失败: {e}')
            ver = ''

    if not ver:
        ver = OFFICIAL_VER
    if not uts_version:
        uts_version = OFFICIAL_UTS_VERSION

    print()
    print('[1/2] 覆盖 include/generated/ 定义（唯一源头）')
    changed = patch_generated(root, ver, uts_version)

    print()
    print('[2/2] 源码兜底替换')
    changed += patch_sources(root, ver, uts_version)

    if not changed:
        print('✗ 没有文件被修改，请检查内核源码结构')
        return 1

    print()
    print(f'  UTS_RELEASE   = {ver}')
    print(f'  UTS_VERSION   = {uts_version}')
    print()

    rc = verify(root)
    if rc != 0:
        return rc

    return 0


if __name__ == '__main__':
    sys.exit(main())
